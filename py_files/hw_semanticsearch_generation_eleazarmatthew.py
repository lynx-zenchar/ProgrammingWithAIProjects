    print("Loading cross-encoder reranking model...")
    reranker = CrossEncoder('cross-encoder/ms-marco-MiniLM-L-6-v2')

    def rag_with_reranking(question: str, retrieve_k: int = 10, rerank_k: int = 3):
        """
        Enhanced RAG pipeline with reranking:
        1. Retrieve retrieve_k candidates via embedding search (broad net)
        2. Re-score with cross-encoder (precision filter)
        3. Keep top rerank_k for generation
        """
        # Step 1: Broad retrieval
        results        = search(question, top_k=retrieve_k, verbose=False)
        candidate_docs = results['text'].tolist()

        # Step 2: Cross-encoder reranking
        pairs         = [[question, doc] for doc in candidate_docs]
        rerank_scores = reranker.predict(pairs)

        # Step 3: Select top rerank_k by reranking score
        ranked_indices = np.argsort(rerank_scores)[::-1][:rerank_k]
        top_docs       = [candidate_docs[i] for i in ranked_indices]
        top_scores     = [rerank_scores[i]  for i in ranked_indices]

