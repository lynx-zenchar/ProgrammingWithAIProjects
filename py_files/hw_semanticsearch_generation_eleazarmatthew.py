"""# 8. Retrieval-Augmented Generation (RAG-Style)

### What is being done?
We combine the retrieval system (Section 5) and the language model (Section 7) into a
full **RAG pipeline**:

1. **Retrieve** the most relevant documents for a business question (semantic search)
2. **Inject** those documents as context into a structured prompt
3. **Generate** a concise, grounded answer using the language model

This mirrors the architecture shown in Chapter 8 of the reference textbook, adapted here
for a business intelligence context.

### Why is this necessary from a business analytics perspective?
A language model answering questions in isolation can produce plausible-sounding but
fabricated answers: a well-known risk called "hallucination". By grounding the model's
response in *retrieved evidence from our actual document corpus*, we dramatically reduce
this risk and make the system's answers **auditable and traceable**,  critical requirements
in a professional consulting context where every claim must be defensible.

### How should decision-makers interpret this?
Each generated answer below is directly supported by documents in the knowledge archive.
The system is not guessing: it is synthesising real intelligence from the corpus. Executives
should note which source documents were retrieved alongside each answer, as these form the
evidential basis for the response and can be cited in client deliverables.

"""

def build_rag_prompt(question: str, context_docs: list, style: str = 'standard') -> str:
    """
    Construct a RAG prompt by injecting retrieved context into a question template.

    Parameters
    ----------
    question     : the business question to answer
    context_docs : list of retrieved document strings
    style        : 'standard' (generic) or 'executive' (structured briefing)
    """
    context = "\n\n".join(
        [f"[Document {i+1}]: {doc[:400]}" for i, doc in enumerate(context_docs)]
    )

    if style == 'executive':
        prompt = (
            f"You are a senior business analyst preparing a briefing for an executive "
            f"committee. Using ONLY the information in the documents below, provide a "
            f"structured, actionable answer to the following business question.\n\n"
            f"Business Question: {question}\n\n"
            f"Relevant Intelligence:\n{context}\n\n"
            f"Executive Summary Answer:"
        )
    else:
        prompt = (
            f"Answer the following question based on the provided documents.\n\n"
            f"Question: {question}\n\n"
            f"Documents:\n{context}\n\n"
            f"Answer:"
        )
    return prompt


def rag_answer(question: str, top_k: int = 3, style: str = 'standard',
               max_tokens: int = 200, verbose: bool = True) -> dict:
    """
    Full RAG pipeline: retrieve → prompt → generate.

    Returns dict with keys: question, retrieved_docs, prompt, answer
    """
    # Step 1: Retrieve relevant documents
    results       = search(question, top_k=top_k, verbose=False)
    retrieved_docs = results['text'].tolist()

    # Step 2: Build the grounded prompt
    prompt = build_rag_prompt(question, retrieved_docs, style=style)

    # Step 3: Generate the answer
    output = generator(prompt, max_new_tokens=max_tokens)[0]['generated_text']

    if verbose:
        print(f"Question : {question}")
        print(f"\n Retrieved {top_k} supporting documents from the knowledge archive.")
        print(f"\n Generated Answer:")
        print(textwrap.fill(output, width=80))
        print("\n" + "─" * 70)

    return {
        'question'      : question,
        'retrieved_docs': retrieved_docs,
        'prompt'        : prompt,
        'answer'        : output
    }

